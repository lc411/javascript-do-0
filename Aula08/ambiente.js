// Declara uma variável 'c' inicializada com 1
var c = 1
// Estrutura do-while: executa o bloco pelo menos uma vez, depois verifica a condição
do {
    // Exibe uma mensagem com o valor de 'c'
    console.log(`Tudo bem? ${c}`)
    // Incrementa 'c' em 1
    c++
} while (c <= 6)  // Repete enquanto 'c' for menor ou igual a 6
